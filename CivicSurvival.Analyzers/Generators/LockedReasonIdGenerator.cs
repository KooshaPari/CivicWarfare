using System.Collections.Generic;
using System.Collections.Immutable;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;

namespace CivicSurvival.Analyzers.Generators;

/// <summary>Emits the reason fields and JSON hook declared by DtoEligibility fields.</summary>
[Generator]
public class LockedReasonIdGenerator : IIncrementalGenerator
{
    private const string AttributeName =
        "CivicSurvival.Core.UI.DomainState.Attributes.DtoEligibilityAttribute";

    /// <inheritdoc />
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var candidates = context.SyntaxProvider.CreateSyntaxProvider(
            static (node, _) => node is TypeDeclarationSyntax declaration &&
                declaration.Members.OfType<FieldDeclarationSyntax>().Any(f => f.AttributeLists.Count > 0),
            static (ctx, _) => GetDto(ctx))
            .Where(static dto => dto != null)
            .Collect();

        context.RegisterSourceOutput(candidates, static (output, dtos) =>
        {
            var emitted = new HashSet<string>();
            foreach (var dto in dtos)
            {
                if (dto == null || !emitted.Add(dto.Identity)) continue;
                output.AddSource(dto.Identity.Replace('.', '_') + ".Eligibility.g.cs",
                    SourceText.From(Generate(dto), Encoding.UTF8));
            }
        });
    }

    private static DtoInfo? GetDto(GeneratorSyntaxContext context)
    {
        var declaration = (TypeDeclarationSyntax)context.Node;
        if (context.SemanticModel.GetDeclaredSymbol(declaration) is not INamedTypeSymbol symbol)
            return null;

        var fields = ImmutableArray.CreateBuilder<EligibilityField>();
        foreach (var field in symbol.GetMembers().OfType<IFieldSymbol>())
        {
            var attribute = field.GetAttributes().FirstOrDefault(a =>
                a.AttributeClass?.ToDisplayString() == AttributeName);
            if (attribute == null || field.Type.SpecialType != SpecialType.System_Boolean)
                continue;

            var reason = attribute.ConstructorArguments.Length >= 3
                ? attribute.ConstructorArguments[2].Value as string ?? ""
                : "";
            fields.Add(new EligibilityField(field.Name, reason,
                reason.Length > 0 && !symbol.GetMembers(reason).Any()));
        }

        if (fields.Count == 0) return null;
        return new DtoInfo(symbol.ToDisplayString(), symbol.ContainingNamespace.ToDisplayString(),
            symbol.Name, symbol.TypeKind == TypeKind.Struct ? "struct" : "class",
            symbol.DeclaredAccessibility == Accessibility.Public ? "public" : "internal",
            fields.ToImmutable());
    }

    private static string Generate(DtoInfo dto)
    {
        var source = new StringBuilder("// <auto-generated/>\n#nullable enable\n");
        source.Append("namespace ").Append(dto.Namespace).AppendLine("\n{");
        source.Append("    ").Append(dto.Accessibility).Append(" partial ").Append(dto.Kind)
            .Append(' ').Append(dto.Name).AppendLine("\n    {");
        var declaredReasons = new HashSet<string>();
        foreach (var field in dto.Fields)
        {
            if (field.EmitReason && declaredReasons.Add(field.Reason))
                source.Append("        public string? @").Append(field.Reason).AppendLine(";");
        }

        source.AppendLine("        partial void WriteEligibility(global::CivicSurvival.Core.UI.DomainState.DomainJsonHelper.JsonWriter w)");
        source.AppendLine("        {");
        var writtenReasons = new HashSet<string>();
        foreach (var field in dto.Fields)
        {
            source.Append("            w.Bool(").Append(SymbolDisplay.FormatLiteral(field.Name, true))
                .Append(", @").Append(field.Name).AppendLine(");");
            if (field.Reason.Length > 0 && writtenReasons.Add(field.Reason))
                source.Append("            w.Str(").Append(SymbolDisplay.FormatLiteral(field.Reason, true))
                    .Append(", @").Append(field.Reason).AppendLine(" ?? string.Empty);");
        }
        source.AppendLine("        }\n    }\n}");
        return source.ToString();
    }

    private record EligibilityField(string Name, string Reason, bool EmitReason);
    private record DtoInfo(string Identity, string Namespace, string Name, string Kind,
        string Accessibility, ImmutableArray<EligibilityField> Fields);
}
